// Given a lesson topic (and its category, from AILearningHub) and a curated-
// resources category, find the single best-matching real video for it —
// or null if nothing indexed matches well enough. Match is a simple word-
// overlap score against real titles, never AI-guessed.
export function findExactVideo(playlistCategory, topic) {
  const list = VIDEO_INDEX[playlistCategory];
  if (!list || !topic) return null;

  const stop = new Set(['the', 'a', 'an', 'of', 'in', 'on', 'to', 'and', 'or', 'for', 'with', 'using', 'is', 'are', 'i', 'ii', 'iii']);
  const words = (s) => s.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(w => w.length > 1 && !stop.has(w));

  const topicWords = words(topic);
  if (topicWords.length === 0) return null;

  let best = null, bestScore = 0;
  for (const v of list) {
    const titleWords = new Set(words(v.title));
    let score = 0;
    for (const w of topicWords) if (titleWords.has(w)) score++;
    // Require most of the topic's words to appear in the title, and at least 1,
    // so short/generic searches don't confidently pick a wrong specific video.
    const ratio = score / topicWords.length;
    if (score > 0 && ratio >= 0.6 && score > bestScore) { best = v; bestScore = score; }
  }
  return best;
}
